// Writes each app's copy of the compiled ABIs (run after `forge build`).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const contractsRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(contractsRoot, "..");
const names = [
  "QudaoFactory", "QudaoVault", "Swapper", "PriceOracle", "RevenueRouter",
  "Referrals", "TheWell", "BuybackBurner", "Reserve",
];
let out = "// Generated by contracts/script/export-abis.mjs — do not edit.\n\n";
for (const name of names) {
  const { abi } = JSON.parse(readFileSync(join(contractsRoot, "out", `${name}.sol`, `${name}.json`), "utf8"));
  out += `export const ${name[0].toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
const targets = [
  join(repo, "server", "src", "abi", "abis.ts"),
  join(repo, "web", "src", "abis", "abis.ts"),
];
for (const target of targets) writeFileSync(target, out);
console.log(`wrote ABIs for ${names.length} contracts to server and web`);
